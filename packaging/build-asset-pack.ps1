<#
.SYNOPSIS
  Собирает пакет игровых ассетов (3D-модели + текстуры) для релизов.

.DESCRIPTION
  Модели и текстуры генерируются скриптами Blender и лежат в res/models
  (около 850 МБ), поэтому они не в git и не попадают в сборки CI — релиз
  выходит без единой 3D-модели.

  Этот скрипт упаковывает локальные ассеты в один zip, который:
   * публикуется один раз как asset релиза;
   * подтягивается CI-шагом при сборке (packaging/fetch-assets.ps1) — и
     тогда в каждом релизе модели есть.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File packaging/build-asset-pack.ps1
  powershell -ExecutionPolicy Bypass -File packaging/build-asset-pack.ps1 -Upload -Tag v5.1.0
#>
[CmdletBinding()]
param(
  [string]$OutputDir = "",
  [string]$Tag = "",
  [switch]$SkipTextures,
  [switch]$Upload
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $OutputDir) { $OutputDir = Join-Path $repoRoot 'dist' }

$version = (Get-Content (Join-Path $repoRoot 'VERSION') -Raw).Trim()
if (-not $Tag) { $Tag = "v$version" }

$stage = Join-Path $OutputDir "assets-stage"
if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
New-Item -ItemType Directory -Force -Path (Join-Path $stage 'res') | Out-Null

$included = @()
if (Test-Path (Join-Path $repoRoot 'res\models')) {
  Write-Host '==> adding res/models'
  Copy-Item -LiteralPath (Join-Path $repoRoot 'res\models') -Destination (Join-Path $stage 'res\models') -Recurse
  $included += 'res/models'
}
if (-not $SkipTextures -and (Test-Path (Join-Path $repoRoot 'res\textures'))) {
  Write-Host '==> adding res/textures'
  Copy-Item -LiteralPath (Join-Path $repoRoot 'res\textures') -Destination (Join-Path $stage 'res\textures') -Recurse
  $included += 'res/textures'
}
if ($included.Count -eq 0) {
  throw 'No local assets found (res/models is generated by the Blender scripts).'
}

$manifest = @"
astro-voyager asset pack
tag: $Tag
version: $version
contents: $($included -join ', ')
generated: (local build)
"@
Set-Content -LiteralPath (Join-Path $stage 'ASSET-PACK.txt') -Value $manifest -Encoding UTF8

$zip = Join-Path $OutputDir "astro-voyager-assets-$Tag.zip"
if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
# tar (bsdtar в Windows 10/11) заметно быстрее Compress-Archive на ~1 ГБ.
$tar = Get-Command tar -ErrorAction SilentlyContinue
if ($tar) {
  Push-Location $stage
  tar -a -c -f $zip .
  Pop-Location
} else {
  Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zip -Force
}
$zipMb = [math]::Round((Get-Item -LiteralPath $zip).Length / 1MB, 1)
Write-Host "==> asset pack: $zip ($zipMb MB)"

if ($Upload) {
  $repo = 'remageht/astro-voyager'
  Write-Host "==> uploading to $repo release $Tag"
  gh release upload $Tag $zip --clobber -R $repo
  Write-Host '    uploaded'
}
